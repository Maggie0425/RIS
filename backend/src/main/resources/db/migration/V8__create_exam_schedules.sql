CREATE TABLE exam_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL UNIQUE,
    scheduled_start TIMESTAMP WITH TIME ZONE NOT NULL,
    station_ae_title VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_exam_schedules_exam
        FOREIGN KEY (exam_id) REFERENCES exams (id),
    CONSTRAINT chk_exam_schedules_station_ae_title
        CHECK (station_ae_title = BTRIM(station_ae_title)
            AND CHAR_LENGTH(station_ae_title) > 0)
);

CREATE INDEX idx_exam_schedules_scheduled_start
    ON exam_schedules (scheduled_start);

CREATE INDEX idx_exam_schedules_station_ae_title
    ON exam_schedules (station_ae_title);

