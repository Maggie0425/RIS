CREATE TABLE exams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL,
    accession_number VARCHAR(50) NOT NULL UNIQUE,
    requested_procedure VARCHAR(200) NOT NULL,
    modality VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ORDERED',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_exams_patient
        FOREIGN KEY (patient_id) REFERENCES patients (id),
    CONSTRAINT fk_exams_created_by
        FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT chk_exams_status
        CHECK (status IN (
            'ORDERED',
            'SCHEDULED',
            'ACQUIRED',
            'REPORTED',
            'COMPLETED',
            'CANCELLED'
        ))
);

CREATE INDEX idx_exams_patient_id ON exams (patient_id);
CREATE INDEX idx_exams_status ON exams (status);

