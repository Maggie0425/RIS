CREATE TABLE reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL UNIQUE,
    author_user_id BIGINT NOT NULL,
    report_text TEXT NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reports_exam
        FOREIGN KEY (exam_id) REFERENCES exams (id),
    CONSTRAINT fk_reports_author_user
        FOREIGN KEY (author_user_id) REFERENCES users (id),
    CONSTRAINT chk_reports_text_not_blank
        CHECK (CHAR_LENGTH(BTRIM(report_text)) > 0)
);

CREATE INDEX idx_reports_author_user_id ON reports (author_user_id);

